// Fee estimator rules for new connection based on HERC Schedule of General Charges
export function calculateNewConnectionEstimate(
  category: string,
  loadKw: number,
  isPrepaidSmartMeter = false
): {
  category: 'domestic' | 'nondomestic' | 'agriculture' | 'industrial_lt' | 'industrial_ht';
  loadKw: number;
  isPrepaidSmartMeter: boolean;
  applicationFee: number;
  acdSecurityDeposit: number;
  serviceConnectionCharges: number;
  meterSecurity: number;
  totalEstimatedCost: number;
  supplyType: 'single_phase' | 'three_phase';
} {
  const isThreePhase = loadKw > 5;
  let appFee = 50;
  let acdPerKw = 500; // Advance Consumption Deposit
  let sccPerKw = 750; // Service Connection Charges (Standard drop up to 150m)
  let meterSec = isThreePhase ? 2500 : 900;

  if (category === 'domestic') {
    // Domestic: ≤ 2 kW: ₹50; > 2 kW: ₹25/kW (min ₹50, max ₹20,000)
    appFee = loadKw <= 2 ? 50 : Math.min(20000, Math.max(50, Math.round(loadKw * 25)));
    // ACD: ₹500/kW for single-phase (≤ 5 kW), ₹750/kW for three-phase (> 5 kW)
    acdPerKw = isThreePhase ? 750 : 500;
    // Prepaid smart meters are exempt from ACD as per HERC regulations!
    if (isPrepaidSmartMeter) {
      acdPerKw = 0;
    }
    sccPerKw = isThreePhase ? 1000 : 750;
    meterSec = isThreePhase ? 2500 : 900;
  } else if (category === 'nondomestic') {
    appFee = loadKw <= 2 ? 100 : Math.min(20000, Math.max(100, Math.round(loadKw * 50)));
    acdPerKw = isPrepaidSmartMeter ? 0 : 1000;
    sccPerKw = 1000;
    meterSec = isThreePhase ? 3000 : 1200;
  } else if (category === 'agriculture') {
    appFee = 50;
    acdPerKw = 300;
    sccPerKw = 1500; // Tubewell infrastructure standard
    meterSec = isThreePhase ? 2200 : 800;
  } else if (category === 'industrial_lt') {
    appFee = 500;
    acdPerKw = 1200;
    sccPerKw = 1200;
    meterSec = 4500;
  } else if (category === 'industrial_ht') {
    appFee = 1000;
    acdPerKw = 1500;
    sccPerKw = 1800;
    meterSec = 15000;
  }

  const applicationFee = appFee;
  const acdSecurityDeposit = Math.round(loadKw * acdPerKw);
  const serviceConnectionCharges = Math.round(loadKw * sccPerKw);
  const meterSecurity = meterSec;
  const totalEstimatedCost = applicationFee + acdSecurityDeposit + serviceConnectionCharges + meterSecurity;

  return {
    category: category as any,
    loadKw,
    isPrepaidSmartMeter,
    applicationFee,
    acdSecurityDeposit,
    serviceConnectionCharges,
    meterSecurity,
    totalEstimatedCost,
    supplyType: isThreePhase ? 'three_phase' : 'single_phase'
  };
}

